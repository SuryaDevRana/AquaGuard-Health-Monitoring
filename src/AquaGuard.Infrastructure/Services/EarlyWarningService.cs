using AquaGuard.Application.EarlyWarnings;
using AquaGuard.Domain.Entities;
using AquaGuard.Domain.Enums;
using AquaGuard.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Options;

namespace AquaGuard.Infrastructure.Services;

public sealed class EarlyWarningService(ApplicationDbContext db, IOptions<EarlyWarningSettings> options) : IEarlyWarningService
{
    private readonly EarlyWarningSettings _settings = options.Value;

    public async Task<int> EvaluateAndCreateWarningsAsync(CancellationToken cancellationToken = default)
    {
        var now = DateTime.UtcNow;
        var reviewFrom = now.AddDays(-_settings.LookbackDays);
        var villages = await db.Villages.AsNoTracking().Select(x => new { x.Id, x.Name }).ToListAsync(cancellationToken);
        var created = 0;

        foreach (var village in villages)
        {
            var diseaseGroups = await db.PatientReports.AsNoTracking()
                .Where(x => x.VillageId == village.Id && x.ReportedOn >= reviewFrom)
                .GroupBy(x => new { x.DiseaseId, x.Disease.Name })
                .Select(x => new { x.Key.DiseaseId, x.Key.Name, Count = x.Count() })
                .Where(x => x.Count >= _settings.ModerateCaseThreshold)
                .ToListAsync(cancellationToken);

            var waterReports = await db.WaterQualityReports.AsNoTracking()
                .Where(x => x.WaterSource.VillageId == village.Id && x.TestingDate >= reviewFrom)
                .ToListAsync(cancellationToken);
            var unsafeReports = waterReports.Where(x => IsUnsafe(x)).ToList();

            foreach (var disease in diseaseGroups)
            {
                var risk = disease.Count >= _settings.CriticalCaseThreshold ? RiskLevel.Critical
                    : disease.Count >= _settings.HighCaseThreshold ? RiskLevel.High : RiskLevel.Moderate;
                if (unsafeReports.Count >= _settings.RepeatedContaminationThreshold && risk < RiskLevel.High)
                {
                    risk = RiskLevel.High;
                }

                var reason = $"{disease.Count} {disease.Name} case reports were recorded in the last {_settings.LookbackDays} days";
                if (unsafeReports.Count > 0)
                {
                    reason += $"; {unsafeReports.Count} water-quality result(s) also require attention.";
                }

                var exists = await db.EarlyWarnings.AnyAsync(x => x.VillageId == village.Id && x.RelatedDiseaseId == disease.DiseaseId &&
                    (x.Status == WarningStatus.Open || x.Status == WarningStatus.Acknowledged) && x.AlertDate >= now.AddDays(-1), cancellationToken);
                if (exists) continue;

                db.EarlyWarnings.Add(CreateWarning(village.Id, risk, reason, disease.DiseaseId, disease.Count));
                created++;
            }

            if (unsafeReports.Count >= _settings.RepeatedContaminationThreshold)
            {
                var exists = await db.EarlyWarnings.AnyAsync(x => x.VillageId == village.Id && x.RelatedDiseaseId == null &&
                    (x.Status == WarningStatus.Open || x.Status == WarningStatus.Acknowledged) && x.AlertDate >= now.AddDays(-1), cancellationToken);
                if (!exists)
                {
                    db.EarlyWarnings.Add(CreateWarning(village.Id, RiskLevel.High,
                        $"{unsafeReports.Count} water-quality reports require attention in the last {_settings.LookbackDays} days.", null, 0));
                    created++;
                }
            }
        }

        if (created > 0)
        {
            await db.SaveChangesAsync(cancellationToken);
        }
        return created;
    }

    private bool IsUnsafe(WaterQualityReport report) => report.Status == QualityStatus.Unsafe
        || report.EColiResult == TestResult.Unsafe
        || report.TotalColiformResult == TestResult.Unsafe
        || (report.PhLevel.HasValue && (report.PhLevel < _settings.MinimumPh || report.PhLevel > _settings.MaximumPh))
        || (report.TurbidityNtu.HasValue && report.TurbidityNtu > _settings.MaximumTurbidityNtu);

    private static EarlyWarning CreateWarning(int villageId, RiskLevel risk, string reason, int? diseaseId, int cases) => new()
    {
        AlertCode = $"AGW-{DateTime.UtcNow:yyyyMMdd}-{Guid.NewGuid().ToString("N")[..6].ToUpperInvariant()}",
        VillageId = villageId,
        RiskLevel = risk,
        TriggerReason = reason,
        RelatedDiseaseId = diseaseId,
        ReportedCaseCount = cases,
        AlertDate = DateTime.UtcNow,
        RecommendedAction = "Validate the reports, arrange appropriate confirmatory testing, and coordinate a local health follow-up. This alert is not a diagnosis or confirmed outbreak.",
        Status = WarningStatus.Open,
        EvidenceSummary = "Automatically generated by transparent, configurable rules for human review."
    };
}
